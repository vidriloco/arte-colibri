export function formatPrice(value, lang, currency = "MXN") {
  if (value == null || value === "") return DICT[lang].on_request;
  const n = typeof value === "string" ? parseFloat(value) : value;
  if (Number.isNaN(n)) return DICT[lang].on_request;
  return new Intl.NumberFormat(lang === "es" ? "es-MX" : "en-US", {
    style: "currency",
    currency,
    maximumFractionDigits: 0,
  }).format(n);
}
